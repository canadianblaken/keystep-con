#!/usr/bin/env python3
"""Write the KeyStep Con page's firmware patch (src/1f-fwpatch.js): only the bytes KSCON changes.

The page takes the user's own copy of Arturia's 2.5.20 update, checks every entry against the stock SHA-256,
applies these runs and checks every result against the tested build, so no Arturia firmware is shipped.
Run after build_ksp_patch.py:
    tools/make_web_patch.py > web/src/1f-fwpatch.js
This tool never contacts or writes to a device.
"""
from __future__ import annotations

import base64
import gzip
import hashlib
import json
import zipfile

from build_ksp_patch import PATCH_BUILD, PATCH_VERSION
from build_names_patch import KSPF, ROOT

BUILT = ROOT / f"firmware/patched/KSCON_2.5.{PATCH_VERSION}_build{PATCH_BUILD}.kspf"


def runs(old: bytes, new: bytes) -> list[tuple[int, int]]:
    """Offsets and lengths of the bytes that differ (anything past the stock length counts as different)."""
    out, i = [], 0
    while i < len(new):
        if i < len(old) and old[i] == new[i]:
            i += 1
            continue
        j = i
        while j < len(new) and not (j < len(old) and old[j] == new[j]):
            j += 1
        out.append((i, j - i))
        i = j
    return out


def main() -> None:
    sha = lambda b: hashlib.sha256(b).hexdigest()
    stock, built = zipfile.ZipFile(KSPF), zipfile.ZipFile(BUILT)
    if [i.filename for i in stock.infolist()] != [i.filename for i in built.infolist()]:
        raise SystemExit("entry lists differ")
    entries, blob = [], bytearray()
    for info in stock.infolist():
        old, new = stock.read(info), built.read(info.filename)
        r = runs(old, new) if old != new else []
        for off, n in r:
            blob += new[off:off + n]
        entries.append({"name": info.filename, "inSha": sha(old), "outSha": sha(new), "len": len(new), "runs": r})
    patch = {"build": PATCH_BUILD, "version": f"2.5.{PATCH_VERSION}", "file": BUILT.name,
             "outZipSha": sha(BUILT.read_bytes()), "entries": entries,
             "blob": base64.b64encode(gzip.compress(bytes(blob), 9, mtime=0)).decode()}
    print(f"/* KSCON firmware patch: generated by tools/make_web_patch.py from {BUILT.name}; only the changed bytes, "
          "no Arturia firmware. Do not edit. */")
    print("const FW_PATCH=" + json.dumps(patch, separators=(",", ":")) + ";")


if __name__ == "__main__":
    main()
