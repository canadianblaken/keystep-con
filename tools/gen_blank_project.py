#!/usr/bin/env python3
"""Write the empty-project template for the manual web app (New empty project).

Source: a whole-project recall from a real KeyStep Pro 2.5.20 (a backup file saved by the web app).
Project 8 of the 2026-10-20 backup had only a name and a chord written by the set list tool, so with the
chord cleared and chord mode off every value is what the firmware itself stored for a fresh project.
    tools/gen_blank_project.py backup.json 8 > web/src/1e-blank.js
The values are stored in recall-plan order (src/1c-bulk.js); the page rebuilds the blocks from the plan.
"""
import base64, gzip, json, sys

backup, num = json.load(open(sys.argv[1])), int(sys.argv[2])
proj = next(p for p in backup['projects'] if p['project'] == num)
CHORD, MODE, TRACKS = 0x57, 0x56, (0x7A, 0x7B, 0x7C, 0x7D, 0x7E)
values = []
for item, param, path, v in proj['data']:
    v = list(v)
    if item in TRACKS and param == CHORD:          # no chord: root 0x7F, offsets 0 (as the device stores it)
        v = [0x7F if path[0] == 1 else 0]
    if item in TRACKS and param == MODE:           # chord mode off
        v = [x & ~0x10 if x is not None else x for x in v]
    if any(x is None for x in v):
        sys.exit(f'unreadable value in block {item}/{param}/{path}; pick another project')
    values.append(v)
blob = base64.b64encode(gzip.compress(json.dumps(values, separators=(',', ':')).encode(), 9, mtime=0)).decode()
print(f'/* empty-project template: generated by ~/kscon/tools/gen_blank_project.py from project {num} of a KeyStep Pro 2.5.20')
print(f'   recall ({backup["saved"][:10]}), chord cleared, chord mode off; {len(values)} blocks in recall-plan order; do not edit */')
print(f'const BLANK_PROJECT_GZ="{blob}";')
