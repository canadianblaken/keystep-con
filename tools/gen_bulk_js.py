#!/usr/bin/env python3
"""Write the KeyStep Pro project-recall plan for the playable manual.

Source: MCC KeyStepPro.json bulkOperation (trailing commas stripped), which lists every
item/param/index block MIDI Control Center reads for a project recall.
    tools/gen_bulk_js.py > web/src/1c-bulk.js

Each block is [lo, hi, item, dims, n, params]: for IDX = lo..hi, for every index path in
the product of dims ("I" = IDX), for every param: one bulk GET/SET of n values.
A plain bulkItemId reads index [1], one value (as the hardware-checked tools do).
"""
import json, re
from pathlib import Path

d = json.loads(re.sub(r',(\s*[\]}])', r'\1', (Path(__file__).parents[1] / 'mcc/KeyStepPro.json').read_text()))


def block(o, lo, hi):
    bi = o['bulkItemId']
    if isinstance(bi, int):
        return [lo, hi, bi, [[1]], 1, o['bulkParamIds']]
    dims = []
    for x in bi[1:-1]:
        if x == 'IDX' or x == ['IDX']:
            dims.append(['I'])
        else:
            dims.append(x if isinstance(x, list) else [x])
    return [lo, hi, bi[0][0], dims, bi[-1], o['bulkParamIds']]


blocks = []
for o in d['bulkOperation']:
    if 'multibulk' in o:
        lo, hi = o['multibulk_idx']
        blocks += [block(m, lo, hi) for m in o['multibulk']]
    else:
        blocks.append(block(o, 0, 0))
print('/* generated by ~/kscon/tools/gen_bulk_js.py from MCC KeyStepPro.json (project recall plan); do not edit */')
print('const BULK=' + json.dumps(blocks, separators=(',', ':')) + ';')
