#!/usr/bin/env python3
"""Write the KeyStep Pro global-settings table for the playable manual.

Source: MCC KeyStepPro.json globalFields (trailing commas stripped) plus the
settings found in firmware 2.5.20 that MCC does not expose (findings.md).
    tools/gen_globals_js.py > web/src/1b-globals.js
"""
import json, re, sys
from pathlib import Path

d = json.loads(re.sub(r',(\s*[\]}])', r'\1', (Path(__file__).parents[1] / 'mcc/KeyStepPro.json').read_text()))
F = {f['id']: f for f in d['fields']}
rows, seen = [], set()
for g in d['globalFields']:
    for fid in g['fields']:
        f = F[fid]
        gid = f.get('globalParamId')
        if f['name'] == 'Empty row' or gid in seen:
            continue
        seen.add(gid)
        r = {'id': gid, 'g': g['group'], 'n': f['name'], 'd': f.get('defaultValue', 0)}
        t = f.get('type')
        if t in ('LIST', 'TEXT_LIST'):
            r['o'] = [[v['val'], v['str']] for v in f['list']]
        elif t == 'CHANNEL':
            r['ch'] = [[v['val'], v['str']] for v in f.get('list', [])]
        elif t == 'NOTE':
            r['note'] = 1
        else:
            r['r'] = [f.get('minValue', 0), f.get('maxValue', 127)]
        rows.append(r)
OFF_ON = [[0, 'OFF'], [1, 'ON']]
hidden = [
    (143, 'Track 1 PC Send (Seq mode)', OFF_ON), (142, 'Track 1 PC Send (Drum mode)', OFF_ON),
    (144, 'Track 2 PC Send', OFF_ON), (145, 'Track 3 PC Send', OFF_ON), (146, 'Track 4 PC Send', OFF_ON),
    (155, 'Track 1 Fixed Velocity (Seq mode)', OFF_ON), (154, 'Track 1 Fixed Velocity (Drum mode)', OFF_ON),
    (156, 'Track 2 Fixed Velocity', OFF_ON), (157, 'Track 3 Fixed Velocity', OFF_ON), (158, 'Track 4 Fixed Velocity', OFF_ON),
    (152, 'Brightness', [[0, 'Very Low'], [1, 'Low'], [2, 'High']]),
    (153, 'Transpose Latch (raw value; the menu stores it inverted)', [[0, '0'], [1, '1']]),
]
for gid, name, opts in hidden:
    rows.append({'id': gid, 'g': 'Not in MCC (firmware 2.5)', 'n': name, 'd': 0, 'o': opts, 'hidden': 1})
print('/* generated by ~/kscon/tools/gen_globals_js.py from MCC KeyStepPro.json + firmware findings; do not edit */')
print('const GLOBALS=' + json.dumps(rows, separators=(',', ':')) + ';')
